"""App passwords: what Subsonic apps log in with instead of the login password (decision D19).

The login password is hashed with argon2 and cannot serve the Subsonic token method, which
needs md5(secret + salt) on the server. App passwords are generated by the server, shown once,
stored encrypted, and revoked one by one, e.g. when a phone is lost.
"""

import hashlib
import hmac
import secrets
from collections.abc import Callable
from dataclasses import dataclass

from sqlalchemy import Connection, delete, func, insert, select, update

from audium.auth.secretbox import SecretBox
from audium.db.schema import app_passwords, users
from audium.errors import BadRequest, NotFound
from audium.services.users import User, normalize_username, user_from_row
from audium.util import now_ms

# Lower case and digits only (easy to type on a phone), without look-alikes (i l o 0 1).
_ALPHABET = "abcdefghjkmnpqrstuvwxyz23456789"
_GROUPS, _GROUP_LEN = 6, 4  # 24 characters, ~119 bits
_PREFIX_LEN = 4
MAX_PER_USER = 50
_TOUCH_MS = 5 * 60 * 1000


@dataclass(frozen=True)
class Match:
    user: User
    password_id: int
    needs_touch: bool


def _context(user_id: int) -> bytes:
    return f"app-password:{user_id}".encode()


def generate() -> str:
    return "-".join("".join(secrets.choice(_ALPHABET) for _ in range(_GROUP_LEN)) for _ in range(_GROUPS))


def _out(row) -> dict:
    return {
        "id": row.id,
        "name": row.name,
        "prefix": row.prefix,
        "created_at": row.created_at,
        "last_used_at": row.last_used_at,
        "last_client": row.last_client,
    }


def list_for_user(conn: Connection, user_id: int) -> list[dict]:
    rows = conn.execute(
        select(app_passwords).where(app_passwords.c.user_id == user_id).order_by(app_passwords.c.id)
    ).all()
    return [_out(r) for r in rows]


def create(conn: Connection, box: SecretBox, user_id: int, name: str) -> tuple[dict, str]:
    """The new entry and the password itself, which is never shown again."""
    clean = " ".join(name.split())[:64]
    if not clean:
        raise BadRequest("name must not be empty")
    count = conn.execute(
        select(func.count()).select_from(app_passwords).where(app_passwords.c.user_id == user_id)
    ).scalar_one()
    if count >= MAX_PER_USER:
        raise BadRequest(f"at most {MAX_PER_USER} app passwords per account; revoke unused ones first")
    password = generate()
    pw_id = conn.execute(
        insert(app_passwords).values(
            user_id=user_id,
            name=clean,
            secret_enc=box.seal(password, _context(user_id)),
            prefix=password[:_PREFIX_LEN],
            created_at=now_ms(),
        )
    ).inserted_primary_key[0]
    row = conn.execute(select(app_passwords).where(app_passwords.c.id == pw_id)).one()
    return _out(row), password


def revoke(conn: Connection, user_id: int, pw_id: int) -> None:
    res = conn.execute(delete(app_passwords).where(app_passwords.c.id == pw_id, app_passwords.c.user_id == user_id))
    if res.rowcount == 0:
        raise NotFound("app password not found")


def plain_check(given: str) -> Callable[[str], bool]:
    return lambda secret: hmac.compare_digest(secret.encode(), given.encode())


def token_check(token: str, salt: str) -> Callable[[str], bool]:
    """Subsonic token method: t = md5(password + s), hex."""
    expected = token.strip().lower().encode()
    return lambda secret: hmac.compare_digest(hashlib.md5((secret + salt).encode()).hexdigest().encode(), expected)  # noqa: S324 - mandated by the protocol


def verify(conn: Connection, box: SecretBox, username: str, check: Callable[[str], bool]) -> Match | None:
    """The active user whose app password passes `check`, or None. Read-only."""
    user_row = conn.execute(select(users).where(users.c.username == normalize_username(username))).first()
    if user_row is None or user_row.status != "active":
        return None
    rows = conn.execute(
        select(app_passwords.c.id, app_passwords.c.secret_enc, app_passwords.c.last_used_at).where(
            app_passwords.c.user_id == user_row.id
        )
    ).all()
    context = _context(user_row.id)
    for r in rows:
        secret = box.open(r.secret_enc, context)
        if secret is not None and check(secret):
            stale = r.last_used_at is None or r.last_used_at + _TOUCH_MS < now_ms()
            return Match(user_from_row(user_row), r.id, stale)
    return None


def touch(conn: Connection, pw_id: int, client: str | None) -> None:
    values: dict = {"last_used_at": now_ms()}
    if client:
        values["last_client"] = client[:64]
    conn.execute(update(app_passwords).where(app_passwords.c.id == pw_id).values(**values))
